# -*- coding: utf-8 -*-
"""Brings in the AI-painted art made for Longmen Tactics (C:\\LongmenTactics, tools/ai_art.py and tools/ai_chibi.py).

    C:/sdenv/Scripts/python -P tools/ai_art.py

    assets/ai/portraits.webp  192 x 224 busts (the 6:7 frame of the pixel portraits), 12 to a row, transparent
    assets/ai/sprites.webp    the painted map figures: front, side, back in 108 x 124 cells, one character a row
                              part; side views stored facing right (the Character Gallery's walk_side convention)
    js/ai_art.js              AI = { gallery id: { p: [x, y] portrait, s: [x, y] sprite strip } }

Ids are the Character Gallery's (the values of KEY in js/art.js). Characters not painted yet are left out and keep
their pixel art; run this again when more paintings arrive (it re-reads everything each time). It also sets the
cache-busting ?v= on the three files (in js/main.js and js/render.js) to a hash of their contents.
"""
import hashlib
import json
import os
import re
import sys

from PIL import Image

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
TAC = 'C:/LongmenTactics'
sys.path.insert(0, os.path.join(TAC, 'tools'))
import ai_chibi  # noqa: E402

ai_chibi.H, ai_chibi.MAXW = 120, 104
PW, PH, PCOLS = 192, 224, 12
CW, CH, SCOLS = 108, 124, 6


def main():
    art = open(os.path.join(ROOT, 'js', 'art.js'), encoding='utf-8').read()
    ids = sorted(set(json.loads(re.search(r'export const KEY = (\{.*?\});', art).group(1)).values()))
    cut, raw = os.path.join(TAC, 'art', 'cut'), os.path.join(TAC, 'art', 'chibi')
    out = os.path.join(ROOT, 'assets', 'ai')
    os.makedirs(out, exist_ok=True)
    idx = {}
    # portraits
    por = [k for k in ids if os.path.exists(os.path.join(cut, k + '_portrait.webp'))]
    sheet = Image.new('RGBA', (PW * PCOLS, PH * max(1, (len(por) + PCOLS - 1) // PCOLS)))
    for n, k in enumerate(por):
        im = Image.open(os.path.join(cut, k + '_portrait.webp')).convert('RGBA')
        w = round(im.height * PW / PH)
        im = im.crop(((im.width - w) // 2, 0, (im.width - w) // 2 + w, im.height)).resize((PW, PH), Image.LANCZOS)
        x, y = (n % PCOLS) * PW, (n // PCOLS) * PH
        sheet.alpha_composite(im, (x, y))
        idx.setdefault(k, {})['p'] = [x, y]
    sheet.save(os.path.join(out, 'portraits.webp'), quality=88, method=6)
    # map figures
    strips = []
    for k in ids:
        paths = [os.path.join(raw, f'{k}_{v}.png') for v in ('front', 'side', 'back')]
        if not all(os.path.exists(p) for p in paths):
            continue
        try:
            views = [ai_chibi.cut(Image.open(p)) for p in paths]
        except (OSError, ValueError):   # still being painted
            continue
        if not all(views):
            continue
        if k not in ai_chibi.PAINTED_RIGHT:
            views[1] = views[1].transpose(Image.FLIP_LEFT_RIGHT)   # painted looking left; stored facing right
        strips.append((k, views))
    sheet = Image.new('RGBA', (CW * 3 * SCOLS, CH * max(1, (len(strips) + SCOLS - 1) // SCOLS)))
    for n, (k, views) in enumerate(strips):
        x, y = (n % SCOLS) * CW * 3, (n // SCOLS) * CH
        for j, im in enumerate(views):
            sheet.alpha_composite(im, (x + j * CW + (CW - im.width) // 2, y + CH - 2 - im.height))
        idx.setdefault(k, {})['s'] = [x, y]
    sheet.save(os.path.join(out, 'sprites.webp'), quality=90, method=6)
    with open(os.path.join(ROOT, 'js', 'ai_art.js'), 'w', encoding='utf-8') as f:
        f.write('// generated by tools/ai_art.py from the AI-painted art of Longmen Tactics - do not edit\n')
        f.write('export const AI = ' + json.dumps(idx, separators=(',', ':')) + ';\n')
    stamp()
    left = [k for k in ids if k not in idx or 's' not in idx[k]]
    print(len(por), 'portraits,', len(strips), 'map figures of', len(ids), '; still pixel art on the map:', ' '.join(left))


def stamp():
    """?v=<content hash> on every URL of the generated files, so browsers fetch them again only when they change."""
    ver = lambda rel: hashlib.sha1(open(os.path.join(ROOT, rel), 'rb').read()).hexdigest()[:8]
    for src in ('js/main.js', 'js/render.js'):
        p = os.path.join(ROOT, src)
        s = open(p, encoding='utf-8', newline='').read()
        n = re.sub(r"(assets/ai/(?:sprites|portraits)\.webp)\?v=\w+", lambda m: m.group(1) + '?v=' + ver(m.group(1)), s)
        n = re.sub(r"(\./ai_art\.js)\?v=\w+", lambda m: m.group(1) + '?v=' + ver('js/ai_art.js'), n)
        if n != s:
            open(p, 'w', encoding='utf-8', newline='').write(n)


if __name__ == '__main__':
    main()
